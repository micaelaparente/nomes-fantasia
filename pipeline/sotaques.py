def limpa(nome):
    ws = [w for w in norm(nome).split() if w not in RUIDO]
    return ' '.join(ws)


def _tokens_bairro(bairro):
    t = {w for w in norm(bairro).split() if w not in GENERICO and len(w) > 2}
    return t | APELIDOS.get(bairro, set())


def classifica(nome, bairro=''):
    ws = nome.split()
    S = set(ws)
    out = set()
    # inglês: léxico, gerúndio -ING e possessivo ("BOB S")
    if S & INGLES or any(len(w) > 5 and w.endswith('ING') for w in ws) or \
            any(ws[i] == 'S' and len(ws[i - 1]) > 2 for i in range(1, len(ws))):
        out.add('ingles')
    # francês / italiano: léxico e grafias (-ERIE, EAU, CC, GLI, ZZ fora de PIZZA)
    if S & EUROPEU or any(w.endswith('ERIE') or ('EAU' in w and 'BEAUT' not in w) or ('GLI' in w and 'GLISH' not in w) or
                          re.search(r'CC[HI]', w) or ('ZZ' in w and not w.startswith('PIZZ')) for w in ws):
        out.add('europeu')
    # exagero / abundância: superlativos e aumentativos
    if S & EXAGERO or S & AUMENT_OK or any(len(w) > 5 and w.endswith('ZAO') for w in ws):
        out.add('exagero')
    # afeto: diminutivos e tratamento familiar; "BAR DO ZE"
    if S & AFETO_PAL or any(len(w) > 5 and re.search(r'(INHO|INHA|ZINHO|ZINHA|INHOS|INHAS)$', w)
                            and w not in NAO_DIMINUTIVO for w in ws) or \
            any(ws[i] in ('DO', 'DA') and ws[i + 1] in PRENOMES for i in range(len(ws) - 1)):
        out.add('afeto')
    fe = S & FE
    if fe == {'FE'} and any(ws[i] == 'FE' and ws[i - 1] == 'SANTA' for i in range(1, len(ws))):
        fe = set()
    if fe or 'DEUS E FIEL' in nome:
        out.add('fe')
    # "RIO" seguido de DO/DA/DAS/DOS é rio ou lugar ("Rio das Pedras"), não a cidade
    rio_lugar = any(ws[i] == 'RIO' and ws[i + 1] in ('DO', 'DA', 'DOS', 'DAS') for i in range(len(ws) - 1))
    carioca = S & CARIOCA - ({'RIO'} if rio_lugar else set())
    if S & _tokens_bairro(bairro) or carioca:
        out.add('bairrismo')
    # nome de gente: sobrenome comum, ou dois prenomes, ou prenome + sobrenome
    pren = sum(w in PRENOMES for w in ws)
    if S & SOBRENOMES or pren >= 2:
        out.add('sobrenome')
    return out


def parece_pessoa(nome):
    """Nome que provavelmente identifica uma pessoa (não deve ir ao mapa)."""
    ws = nome.split()
    # SCP/SPE com nome próprio: sociedades de pessoas físicas (consultórios, investidores)
    if {'SCP', 'SPE'} & set(ws):
        return True
    pren = sum(w in PRENOMES for w in ws)
    sob = sum(w in SOBRENOMES for w in ws)
    return (pren + sob >= 2) or (len(ws) <= 2 and pren + sob >= 1 and not any(w in INGLES | EUROPEU for w in ws))
