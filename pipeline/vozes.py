def classifica(nome, cru=''):
    ws = nome.split()
    S = set(ws)
    out = set()

    if any(len(w) > 4 and re.search(r'(INHO|INHA|INHOS|INHAS)$', w) and w not in NAO_DIM for w in ws):
        out.add('diminutivo')

    if S & AUMENT or any(len(w) > 5 and w.endswith('ZAO') and w not in NAO_AUMENT for w in ws):
        out.add('aumentativo')

    for i, w in enumerate(ws):
        if w not in REALEZA:
            continue
        seguinte = ws[i + 1] if i + 1 < len(ws) else ''
        if w in TITULO_RUA and seguinte in ('DE', 'DO', 'DA', 'DOS', 'ISABEL', 'LEOPOLDINA'):
            continue
        out.add('realeza')
        break

    # inglês: léxico do sotaques, gerúndio -ING e possessivo ("BOB'S")
    if S & INGLES or any(len(w) > 5 and w.endswith('ING') for w in ws) or "'S" in cru.upper() or '’S' in cru.upper():
        out.add('ingles')

    # francês: léxico e grafias (-ERIE, EAU, -EUR); "LE"/"LES" só junto de outra palavra francesa ou no início
    fr = S & FRANCES
    if fr <= P('LE LES DU DES AU AUX MON VIE ELLE'):
        fr = fr if ws and ws[0] in ('LE', 'LES', 'CHEZ') else set()
    if fr or any((w.endswith('ERIE') and w != 'LINGERIE') or ('EAU' in w and 'BEAUT' not in w) for w in ws):
        out.add('frances')

    sem_lugar = LUGAR_SANTO.sub(' ', nome)
    sw = sem_lugar.split()
    santo = any(sw[i] in ('SAO', 'SANTO', 'SANTA') and sw[i + 1] in SANTOS for i in range(len(sw) - 1))
    fe = set(sw) & FE
    if 'FE' in fe and not re.search(r'\b(DE|COM|NA|PELA) FE\b|\bFE (EM|E|NA|DE) (DEUS|JESUS|CRISTO|VIDA)\b', sem_lugar):
        fe.discard('FE')
    if fe or santo or DEVOCAO.search(nome):
        out.add('fe')

    if re.search(r'[?!]', cru) or S & VERBOS or S & INTERJ or EXPR.search(nome):
        out.add('frases')

    if S & MIGRACAO or re.search(r'\bDO (MINEIRO|BAIANO|PARAIBA|CEARA|GAUCHO|PORTUGUES|TURCO|JAPA|ARABE)\b', nome):
        out.add('migracao')

    if S & PARENTESCO or re.search(r'\b(E|PAI E|MAE E) FILHOS?\b|\bFILHO E\b', nome):
        out.add('parentesco')

    return out


