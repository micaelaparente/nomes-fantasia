def tipo_de_frase(nome):
    """Chamados, promessas, primeira pessoa ou interjeições; nada quando só bateu ruído (Chama Gás, Bom Gosto, JA Alves)."""
    S = set(nome.split())
    if TO_INGLES.search(nome) or ('TO' in S and len(S & INGLES) >= 1):
        S.discard('TO')
    if S & F_INTERJ or F_SAUDACAO.search(nome) or re.search(r'\bOH MY\b', nome):   # "Oh my" sim; "Yes", "Oh Beach" não
        return 'interjeicoes'
    if S & F_PRIMEIRA:
        return 'primeira'
    if S & F_CHAMADO:
        return 'chamados'
    if F_PROMESSA.search(nome):
        return 'promessas'
    return None


def classifica_conceitos(nome, cru=''):
    """Subcategorias dos cinco conceitos. Fé fica numa só tradição (a mais específica); a frase, num só tipo."""
    base = classifica(nome, cru)
    ws = nome.split()
    S = set(ws)
    out = {v for v in ('aumentativo', 'diminutivo', 'ingles', 'frances') if v in base}
    if 'frases' in base and (f := tipo_de_frase(nome)):
        out.add(f)
    if 'parentesco' in base:
        graus = {g for g, lex in PARENTES.items() if S & lex}
        out |= graus or {'filhos'}            # "& FILHOS", "PAI E FILHO" sem outra palavra caem em filhos
    if 'fe' in base or S & AFRO or AFRO_EXPR.search(nome):
        # rua com nome de santa, sobrenome "dos Anjos"/"de Deus", "Power Axe" (inglês) não são fé
        sem_lugar = re.sub(r'\b(AVENIDA|RUA|AV) NOSSA SENHORA\b|\bDOS ANJOS\b|\b[A-Z]+ DE DEUS\b(?<!BENCAO DE DEUS)|\bPOWER AXE\b', ' ',
                           LUGAR_SANTO.sub(' ', nome))
        S = set(sem_lugar.split())
        sw = sem_lugar.split()
        santo = any(sw[i] in ('SAO', 'SANTO', 'SANTA') and sw[i + 1] in SANTOS for i in range(len(sw) - 1))
        if S & EVANGELICO or 'DEUS E FIEL' in nome or re.search(r'\bEL SHAD', nome):
            out.add('evangelico')
        elif santo or CATOLICO_EXPR.search(sem_lugar):
            out.add('catolico')
        elif S & AFRO or AFRO_EXPR.search(nome):
            out.add('afro')
        elif set(sw) & CRISTAO or re.search(r'\b(DE|COM|NA) FE\b', sem_lugar):
            out.add('cristao')
    if S & INTERNA or re.search(r'\bDO (MINEIRO|BAIANO|PARAIBA|CEARA|GAUCHO)\b', nome):
        out.add('migracao')
    if S & IMIGRACAO or re.search(r'\bD ITALIA\b|\bDO (PORTUGUES|TURCO|JAPA|ARABE)\b', nome):
        out.add('imigracao')
    return out
