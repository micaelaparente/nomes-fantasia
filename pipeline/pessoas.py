# não contam como palavra do nome: sufixos societários, conectivos e iniciais
RUIDO = set('ME MEI EPP LTDA EIRELI SA CIA DE DA DO DOS DAS E D'.split())
CONECTIVOS = set('DE DA DO DOS DAS'.split())
# antes de um prenome, fazem dele um santo ou um lugar ("São Jorge de Rocha Miranda", "N S de Fátima", "Vila Isabel")
SANTO = set('SAO SANTO SANTA SRA S VILA'.split())
APELIDO = set('ZE ZECA'.split())
RARA = 10  # palavra que aparece em menos de RARA nomes do universo: provavelmente sobrenome fora do léxico


def norm(s):
    s = unicodedata.normalize('NFKD', s or '').encode('ascii', 'ignore').decode().upper()
    return re.sub(r'\s+', ' ', re.sub(r'[^A-Z0-9 ]', ' ', s)).strip()


def eh_nome(w):
    return w in PRENOMES or w in SOBRENOMES


def motivo_pessoa(nome, freq):
    """Por que o nome identifica uma pessoa ('cpf', 'só nome', 'nome completo'); None se não identifica.

    freq: em quantos nomes do universo cada palavra aparece (para reconhecer sobrenomes fora do léxico).
    """
    if re.search(r'\d{11}', nome):
        return 'cpf'
    ws = norm(nome).split()
    # só nome: todas as palavras são prenome ou sobrenome, e ao menos uma é prenome ("Marcia Pinheiro", "Sheila & Fabio")
    toks = [w for w in ws if w not in RUIDO and not w.isdigit() and len(w) > 1]
    if toks and all(eh_nome(w) for w in toks) and any(w in PRENOMES for w in toks):
        return 'só nome'
    # nome completo: um prenome seguido de sobrenome, de outro prenome ou de palavra rara, com ou sem "de"
    # ("Sandra Lima Manicure", "Studio Ricardo Moreira", "Douglas dos Santos Atayde")
    for i, w in enumerate(ws):
        if w not in PRENOMES or (i > 0 and ws[i - 1] in SANTO):
            continue
        j = i + 1
        if j < len(ws) and ws[j] in CONECTIVOS:
            j += 1
        if j >= len(ws):
            continue
        seg = ws[j]
        # depois de Zé, palavra rara é apelido, não sobrenome ("Zé Arruela", "Zé Poderoso", "Zé Pilintra")
        rara = seg.isalpha() and len(seg) > 2 and freq.get(seg, 0) < RARA and w not in APELIDO
        if seg in SOBRENOMES or (seg in PRENOMES and j == i + 1) or rara:
            return 'nome completo'
    return None
